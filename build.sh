#!/bin/zsh
set -euo pipefail
task_source_dir="${0:A:h}"
task_output_dir="${1:-$task_source_dir/dist}"
task_app_dir="$task_output_dir/TouchPDF.app"
task_cache_dir="$task_source_dir/.build/swift-module-cache"
task_bridge_object="$task_source_dir/.build/ProbeBridge.o"
mkdir -p "$task_app_dir/Contents/MacOS" "$task_app_dir/Contents/Resources" "$task_cache_dir"
xcrun clang -std=c11 -Wall -Wextra -O2 -target arm64-apple-macosx13.0 -c "$task_source_dir/ProbeBridge.c" -o "$task_bridge_object"
xcrun swiftc -swift-version 5 -O -target arm64-apple-macosx13.0 -module-cache-path "$task_cache_dir" -import-objc-header "$task_source_dir/ProbeBridge.h" "$task_source_dir/main.swift" "$task_source_dir/RawTrackpadInput.swift" "$task_bridge_object" -framework AppKit -framework PDFKit -framework UniformTypeIdentifiers -framework CoreGraphics -o "$task_app_dir/Contents/MacOS/TouchPDF"
cp "$task_source_dir/Info.plist" "$task_app_dir/Contents/Info.plist"
cp "$task_source_dir/THIRD_PARTY_NOTICES.md" "$task_app_dir/Contents/Resources/THIRD_PARTY_NOTICES.md"
cp "$task_source_dir/LICENSE" "$task_app_dir/Contents/Resources/LICENSE"
/usr/bin/codesign --force --sign - "$task_app_dir"
print "Built: $task_app_dir"
print "Run checks from the app: 帮助 → 运行自检"
